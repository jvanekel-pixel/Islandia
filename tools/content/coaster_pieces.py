#!/usr/bin/env python3
"""Write `CoasterPieces.g.cs` from the coaster track pieces and the pack's measured facts.

`content/rides/coaster-track.yaml` names the pieces a player builds with; each is a model from the
owner's Coaster Kit as `tools/content/measure_coaster_kit.py` measured it into
`content/facts/rides/coaster-kit.json`. The generated file carries both into `Island.Core` as
constants, the same trade `generate_ids.py` makes: Unity and `dotnet build` need no Python, and CI
fails if the file is stale. Reversing and mirroring a model into a piece happens in C#
(`TrackPiece.Place`), where the tests can reach it.

Usage:
    python3 tools/content/coaster_pieces.py          # write the file
    python3 tools/content/coaster_pieces.py --check  # fail if it would change, or the data is wrong
"""

from __future__ import annotations

import json
import re
import sys
import zlib
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent.parent
PIECES = REPO / "content/rides/coaster-track.yaml"
FACTS = REPO / "content/facts/rides/coaster-kit.json"
GENERATED = REPO / "Packages/com.island.core/Runtime/Rides/CoasterPieces.g.cs"

ID = re.compile(r"^coaster(\.[a-z0-9]+)+$")
PLACED = {"as-is": "AsIs", "reversed": "Reversed", "mirrored": "Mirrored", "mirrored-reversed": "MirroredReversed"}
ROLES = {"track": "Track", "station": "Station", "lift": "Lift"}
INTENSITIES = {"gentle": "Gentle", "lively": "Lively", "thrilling": "Thrilling"}
FIELDS = {"id", "name", "shape", "placed", "role", "intensity"}


def symbol(text: str) -> str:
    """`coaster.turn.small.right` -> `TurnSmallRight`; `corner-small` -> `CornerSmall`."""
    parts = re.split(r"[.\-]", text)
    if parts[0] == "coaster":
        parts = parts[1:]
    return "".join(part.capitalize() for part in parts)


def problems(pieces: dict, facts: dict) -> list[str]:
    found: list[str] = []
    shapes = facts.get("shapes", {})
    if facts.get("sub_units_per_unit") != 64:
        found.append("facts: sub_units_per_unit must be 64, which Island.Core is written against")
    seen_ids: dict[int, str] = {}
    seen_symbols: set[str] = set()
    stations = 0
    for index, piece in enumerate(pieces.get("pieces", [])):
        where = f"piece {index + 1} ({piece.get('id', '?')})"
        if set(piece) != FIELDS:
            found.append(f"{where}: fields must be exactly {', '.join(sorted(FIELDS))}")
            continue
        if not ID.match(piece["id"]):
            found.append(f"{where}: id must be lowercase, dotted, and start with 'coaster.'")
        number = zlib.crc32(piece["id"].encode("utf-8")) & 0xFFFFFFFF
        if number == 0 or number in seen_ids:
            found.append(f"{where}: numeric id {number:#010x} is zero or collides with {seen_ids.get(number)}")
        seen_ids[number] = piece["id"]
        if symbol(piece["id"]) in seen_symbols:
            found.append(f"{where}: generates the C# name {symbol(piece['id'])} twice")
        seen_symbols.add(symbol(piece["id"]))
        if piece["shape"] not in shapes:
            found.append(f"{where}: shape {piece['shape']!r} is not in the facts")
        if piece["placed"] not in PLACED:
            found.append(f"{where}: placed must be one of {', '.join(PLACED)}")
        if piece["role"] not in ROLES:
            found.append(f"{where}: role must be one of {', '.join(ROLES)}")
        if piece["intensity"] not in INTENSITIES:
            found.append(f"{where}: intensity must be one of {', '.join(INTENSITIES)}")
        stations += piece["role"] == "station"
    if stations != 1:
        found.append(f"there must be exactly one station piece; found {stations}")
    for name, shape in shapes.items():
        samples = shape.get("samples", [])
        if len(samples) < 2 or samples[0] != [0, 0, 0]:
            found.append(f"facts: {name}'s centreline must start at its entry")
        elif samples[-1] != [shape["exit"]["at"][i] - shape["entry"]["at"][i] for i in range(3)]:
            found.append(f"facts: {name}'s centreline does not end at its exit")
    return found


def render(pieces: dict, facts: dict) -> str:
    out = [
        "// <auto-generated>\n",
        "//     Written by tools/content/coaster_pieces.py from content/rides/coaster-track.yaml and\n",
        "//     content/facts/rides/coaster-kit.json. Do not edit. Run `make content`; CI fails if stale.\n",
        "// </auto-generated>\n\n",
        "namespace Island.Core.Rides\n{\n",
        f"    /// <summary>The {facts['pack']} models, as measured. Positions and lengths in sub-units.</summary>\n",
        "    public static class CoasterShapes\n    {\n",
        "        /// <summary>Sub-units in one pack unit.</summary>\n",
        f"        public const int SubUnitsPerUnit = {facts['sub_units_per_unit']};\n\n",
    ]
    for name, shape in facts["shapes"].items():
        e, x = shape["entry"], shape["exit"]
        samples = ", ".join(str(c) for point in shape["samples"] for c in point)
        supports = ", ".join(str(i) for i in shape["supports"])
        out.append(
            f"        public static readonly TrackShape {symbol(name)} = new TrackShape(\"{name}\", \"{shape['model']}\",\n"
            f"            new TrackPoint({', '.join(map(str, e['at']))}), {e['pitch']}, {e['bank']},\n"
            f"            new TrackPoint({', '.join(map(str, x['at']))}), {x['heading']}, {x['pitch']}, {x['bank']},\n"
            f"            {shape['length']}, {shape['reach']},\n"
            f"            new[] {{ {samples} }},\n"
            f"            new[] {{ {supports} }});\n\n"
        )
    out.append("    }\n\n")
    out.append("    /// <summary>Every piece a coaster can be built from, by its permanent id.</summary>\n")
    out.append("    public static partial class CoasterPieces\n    {\n")
    for piece in pieces["pieces"]:
        out.append(
            f"        public static readonly TrackPiece {symbol(piece['id'])} = TrackPiece.Place(CoasterShapes.{symbol(piece['shape'])},\n"
            f"            \"{piece['id']}\", \"{piece['name']}\", Placement.{PLACED[piece['placed']]}, "
            f"TrackRole.{ROLES[piece['role']]}, RideIntensity.{INTENSITIES[piece['intensity']]});\n"
        )
    out.append("\n        /// <summary>Every piece, in the order the palette lists them.</summary>\n")
    out.append("        public static readonly TrackPiece[] All =\n        {\n")
    out.extend(f"            {symbol(piece['id'])},\n" for piece in pieces["pieces"])
    out.append("        };\n    }\n}\n")
    return "".join(out)


def main(argv: list[str]) -> int:
    checking = "--check" in argv
    pieces = yaml.safe_load(PIECES.read_text(encoding="utf-8"))
    facts = json.loads(FACTS.read_text(encoding="utf-8"))
    found = problems(pieces, facts)
    if found:
        for problem in found:
            print(f"coaster pieces: {problem}")
        return 1
    wanted = render(pieces, facts)
    current = GENERATED.read_text(encoding="utf-8") if GENERATED.is_file() else None
    count = len(pieces["pieces"])
    if current == wanted:
        print(f"coaster pieces: {GENERATED.relative_to(REPO)} is current ({count} pieces)")
        return 0
    if checking:
        print(f"coaster pieces: {GENERATED.relative_to(REPO)} is stale. Run: make content")
        return 1
    GENERATED.parent.mkdir(parents=True, exist_ok=True)
    GENERATED.write_text(wanted, encoding="utf-8")
    print(f"coaster pieces: wrote {GENERATED.relative_to(REPO)} ({count} pieces)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
