#!/usr/bin/env python3
"""Write `CatalogueIds.g.cs` from the catalogue.

Runtime code needs to name a catalogue item without quoting a string that nothing checks. A
generated file of constants gives it that, and makes a typo a compile error instead of a placement
that silently does nothing.

The file is generated, committed, and checked for staleness in CI (`make content-check`). Committing
a generated file is a deliberate trade: it means Unity and `dotnet build` need no Python to compile
the project, and the cost is one check that it is current.

Usage:
    python3 tools/content/generate_ids.py          # write the file
    python3 tools/content/generate_ids.py --check  # fail if it would change
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from catalogue import REPO, Catalogue, Item, load  # noqa: E402

GENERATED = REPO / "Packages/com.island.core/Runtime/Content/CatalogueIds.g.cs"

HEADER = """// <auto-generated>
//     Written by tools/content/generate_ids.py from content/catalogue/*.yaml.
//     Do not edit. Run `make content` after changing the catalogue; CI fails if this is stale.
//
//     Each constant is CRC-32 of the item's id string, so adding an item never renumbers an
//     existing one and a saved island keeps meaning what it meant. See content/catalogue/README.md.
// </auto-generated>

namespace Island.Core.Content
{
    /// <summary>Every placeable item in the catalogue, by its permanent numeric id.</summary>
    public static class CatalogueIds
    {
"""

FOOTER = """    }
}
"""


def render(catalogue: Catalogue) -> str:
    lines = [HEADER]

    if not catalogue.items:
        lines.append("        // The catalogue is empty. Content arrives with C-02 and C-03.\n\n")
    else:
        for category, items in catalogue.by_category().items():
            if not items:
                continue
            lines.append(f"        // {category}\n")
            for item in items:
                lines.append(f"        /// <summary>{_escape(item.name)}</summary>\n")
                lines.append(
                    f"        public const uint {item.symbol} = {item.numeric_id:#010x}u;"
                    f" // {item.id}\n"
                )
            lines.append("\n")

    lines.append(_all_ids(catalogue.items))
    lines.append(FOOTER)
    return "".join(lines)


def _all_ids(items: tuple[Item, ...]) -> str:
    """An array of every id, so a test can assert the generated set matches the catalogue."""
    if not items:
        return "        /// <summary>Every id in the catalogue, ordered by id string.</summary>\n" \
               "        public static readonly uint[] All = new uint[0];\n"

    body = "".join(
        f"            {item.numeric_id:#010x}u, // {item.id}\n" for item in items
    )
    return (
        "        /// <summary>Every id in the catalogue, ordered by id string.</summary>\n"
        "        public static readonly uint[] All =\n        {\n"
        f"{body}"
        "        };\n"
    )


def _escape(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def main(argv: list[str]) -> int:
    checking = "--check" in argv
    catalogue = load()

    if not catalogue.ok:
        print("content: the catalogue does not load, so ids cannot be generated:")
        for problem in catalogue.problems:
            print(f"  {problem}")
        return 1

    wanted = render(catalogue)
    current = GENERATED.read_text(encoding="utf-8") if GENERATED.is_file() else None

    if checking:
        if current == wanted:
            print(f"content: {GENERATED.relative_to(REPO)} is current ({len(catalogue.items)} ids)")
            return 0
        print(f"content: {GENERATED.relative_to(REPO)} is stale. Run: make content")
        return 1

    if current == wanted:
        print(f"content: {GENERATED.relative_to(REPO)} already current ({len(catalogue.items)} ids)")
        return 0

    GENERATED.parent.mkdir(parents=True, exist_ok=True)
    GENERATED.write_text(wanted, encoding="utf-8")
    print(f"content: wrote {GENERATED.relative_to(REPO)} ({len(catalogue.items)} ids)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
